    private void btnRegistrarAsistenteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarAsistenteActionPerformed
String nombre = txtNombre.getText();

if (indice < listaAsistentes.length) {

    listaAsistentes[indice] = nombre;

    txLista.append((indice + 1) + ". " + nombre + "\n");

    indice++;

    txtNombre.setText("");

} else {

    JOptionPane.showMessageDialog(this,
            "Ya se registraron los 5 asistentes");

}


        // TODO add your handling code here:
    }//GEN-LAST:event_btnRegistrarAsistenteActionPerformed

    private void btnExportarListaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarListaActionPerformed

if (indice < 5) {

    JOptionPane.showMessageDialog(this,
            "Debe registrar los 5 asistentes");

    return;
}
File carpeta = new File("temp");

if (!carpeta.exists()) {
    carpeta.mkdir();
}
 try {

        FileWriter archivo =
                new FileWriter("temp/Jhona_asistencia.txt");

        archivo.write("Lista de Asistencia\n\n");

        for (int i = 0; i < listaAsistentes.length; i++) {

            archivo.write((i + 1) + ". "
                    + listaAsistentes[i] + "\n");

        }

        archivo.close();

        JOptionPane.showMessageDialog(this,
                "Lista exportada correctamente");

    } catch (IOException e) {

        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());

    }
}

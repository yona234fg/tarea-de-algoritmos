    public void cargarDiscos() {

    try {

        File archivo = new File("datos/discos.csv");

        Scanner sc = new Scanner(archivo);

        cantidad = 0;

        while (sc.hasNextLine()) {

            String linea = sc.nextLine();

            String[] partes = linea.split(",");

            titulos[cantidad] = partes[0];
            anios[cantidad] = Integer.parseInt(partes[1]);

            cantidad++;
        }

        sc.close();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
    }
}
    
